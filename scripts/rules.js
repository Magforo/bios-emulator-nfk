// Function to change language
function changeLanguage(lang) {
  // Save selected language to localStorage
  localStorage.setItem('preferredLanguage', lang);
  
  // Update HTML lang attribute
  document.documentElement.lang = lang;
  
  // Update page title
  document.title = translations[lang].pageTitle;
  
  // Update login button
  const loginBtn = document.querySelector('.login-btn');
  if (loginBtn) {
    loginBtn.textContent = translations[lang].loginBtn;
  }
  
  // Update publication date
  const pubDate = document.querySelector('.publication-date span');
  if (pubDate) {
    pubDate.textContent = translations[lang].published;
  }

  // Update elements by ID where present (explicit mapping)
  const idMap = {
    pubDate: 'published',
    mainTitle: 'mainTitle',
    introEffective: 'effectiveDate',
    introPrev: 'previousVersion',
    introThankYou: 'thankYou',
    introTerms: 'termsIntro',
    introEEZ: 'eezNotice',
    introPrivacy: 'privacyPolicy',
    servicesTitle: 'servicesTitle',
    servicesPara1: 'whatYouCanText',
    servicesPara2: 'whatYouCannotText',
    rule1: 'rule1',
    rule2: 'rule2',
    rule3: 'rule3',
    rule4: 'rule4',
    rule5: 'rule5',
    rule6: 'rule6'
  };

  Object.keys(idMap).forEach(id => {
    const el = document.getElementById(id);
    const key = idMap[id];
    if (!el || !translations[lang][key]) return;

    // Special handling for some nodes that include links or strong text
    if (id === 'introEffective') {
      el.innerHTML = `${translations[lang].effectiveDate} `;
    } else if (id === 'servicesPara1') {
      el.innerHTML = `<strong>${translations[lang].whatYouCan}</strong> ${translations[lang].whatYouCanText}`;
    } else if (id === 'servicesPara2') {
      el.innerHTML = `<strong>${translations[lang].whatYouCannot}</strong> ${translations[lang].whatYouCannotText}`;
    } else {
      // Default: set textContent
      el.textContent = translations[lang][key];
    }
  });
  
  // Update main title
  const mainTitle = document.querySelector('.main-title');
  if (mainTitle) {
    mainTitle.textContent = translations[lang].mainTitle;
  }
  
  // Update print button
  const printBtn = document.querySelector('.print-btn');
  if (printBtn) {
    printBtn.textContent = translations[lang].printBtn;
  }

  // Also ensure the printBtn element variable (if created but not appended yet) has the right text
  if (typeof printBtn === 'undefined' && window.printBtn) {
    window.printBtn = window.printBtn || null;
  }
  
  // Update all section titles and content dynamically
  updateSectionContent(lang);
  
  // Update footer links
  updateFooterLinks(lang);
}

// Function to update section content
function updateSectionContent(lang) {
  const sections = document.querySelectorAll('.section');
  
  sections.forEach((section, index) => {
    const titles = section.querySelectorAll('.section-title');
    const paragraphs = section.querySelectorAll('.content-text, .intro-text');
    const lists = section.querySelectorAll('.rules-list li');
    
    // Update section titles based on index
    if (index === 0) {
      // Introduction section
      if (paragraphs[0]) {
        paragraphs[0].innerHTML = `${translations[lang].effectiveDate}`;
      }
      if (paragraphs[1]) paragraphs[1].textContent = translations[lang].thankYou;
      if (paragraphs[2]) paragraphs[2].textContent = translations[lang].termsIntro;
      if (paragraphs[3]) paragraphs[3].textContent = translations[lang].eezNotice;
      if (paragraphs[4]) paragraphs[4].textContent = translations[lang].privacyPolicy;
    } else if (index === 1) {
      // Services section
      if (titles[0]) titles[0].textContent = translations[lang].servicesTitle;
      if (paragraphs[0]) {
        paragraphs[0].innerHTML = `<strong>${translations[lang].whatYouCan}</strong> ${translations[lang].whatYouCanText}`;
      }
      if (paragraphs[1]) {
        paragraphs[1].innerHTML = `<strong>${translations[lang].whatYouCannot}</strong> ${translations[lang].whatYouCannotText}`;
      }
      // Update list items
      if (lists[0]) lists[0].textContent = translations[lang].rule1;
      if (lists[1]) lists[1].textContent = translations[lang].rule2;
      if (lists[2]) lists[2].textContent = translations[lang].rule3;
      if (lists[3]) lists[3].textContent = translations[lang].rule4;
      if (lists[4]) lists[4].textContent = translations[lang].rule5;
      if (lists[5]) lists[5].textContent = translations[lang].rule6;
    } else if (index === 2) {
      // Content section
      if (titles[0]) titles[0].textContent = translations[lang].contentTitle;
      if (paragraphs[0]) paragraphs[0].textContent = translations[lang].contentText;
    } else if (index === 3) {
      // Disclaimer section
      if (titles[0]) titles[0].textContent = translations[lang].disclaimerTitle;
      if (paragraphs[0]) paragraphs[0].textContent = translations[lang].disclaimerText;
    } else if (index === 4) {
      // Limitation section
      if (titles[0]) titles[0].textContent = translations[lang].limitationTitle;
    } else if (index === 5) {
      // Termination section
      if (titles[0]) titles[0].textContent = translations[lang].terminationTitle;
    } else if (index === 6) {
      // Amendment section
      if (titles[0]) titles[0].textContent = translations[lang].amendmentTitle;
    } else if (index === 7) {
      // Contact section
      if (titles[0]) titles[0].textContent = translations[lang].contactTitle;
    }
  });
}

// Function to update footer links
function updateFooterLinks(lang) {
  const footerLinks = document.querySelectorAll('.footer-link');
  if (footerLinks[0]) footerLinks[0].textContent = translations[lang].termsOfService;
  if (footerLinks[1]) footerLinks[1].textContent = translations[lang].privacyPolicyLink;
  if (footerLinks[2]) footerLinks[2].textContent = translations[lang].disclaimerLink;
}

